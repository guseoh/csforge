-- Personal-only classification. ConceptProgress.bookmarked stays the single source of truth.
CREATE TABLE bookmark_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT bookmark_category_name_uk UNIQUE (name),
    CONSTRAINT bookmark_category_order_uk UNIQUE (display_order),
    CONSTRAINT bookmark_category_name_nonblank_ck CHECK (length(btrim(name)) > 0)
);

-- Each bookmarked Concept may have at most ONE optional category.
-- Unbookmarking explicitly removes the assignment; deleting personal progress cascades it.
CREATE TABLE bookmark_category_concept (
    concept_id BIGINT PRIMARY KEY,
    category_id BIGINT NOT NULL,
    CONSTRAINT bookmark_category_concept_progress_fk FOREIGN KEY (concept_id)
        REFERENCES concept_progress (concept_id) ON DELETE CASCADE,
    CONSTRAINT bookmark_category_concept_category_fk FOREIGN KEY (category_id)
        REFERENCES bookmark_category (id) ON DELETE RESTRICT
);

CREATE INDEX bookmark_category_concept_category_idx
    ON bookmark_category_concept (category_id, concept_id);

